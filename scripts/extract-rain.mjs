// Copies the real daily rainfall out of the prototype into src/data/rain.ts.
// Run it again only if the prototype's rainfall data changes: npm run extract-rain
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const html = readFileSync(process.env.PROTOTYPE || here('../../game-prototype/earthmoving-sim.html'), 'utf8');

const alpha = html.match(/var WX_AL = '([^']+)'/)[1];
const towns = {};
for (const m of html.matchAll(/(gdi|ct):'([0-9A-Za-z_-]{1000,})'/g)) towns[m[1]] = m[2];
if (!towns.gdi || !towns.ct) throw new Error('Could not find the rainfall strings in the prototype.');

const out = `// Real daily rainfall, 1995 to 2024, from the Open-Meteo historical weather archive.
// One character a day, starting 1 January 1995: its position in RAIN_ALPHABET is the mm that fell (capped at 63).
// Generated by scripts/extract-rain.mjs. Don't edit by hand.

export const RAIN_ALPHABET = '${alpha}';
export const RAIN_FROM = Date.UTC(1995, 0, 1);

export const RAIN = {
  gdi: '${towns.gdi}',
  ct: '${towns.ct}',
} as const;
`;
writeFileSync(here('../src/data/rain.ts'), out);
console.log(`Wrote rainfall: Goondiwindi ${towns.gdi.length} days, Charters Towers ${towns.ct.length} days.`);
