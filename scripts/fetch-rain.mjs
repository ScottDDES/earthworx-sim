// Fetches real daily rainfall, 1995 to 2024, from the Open-Meteo historical weather archive for the Queensland
// towns added after the prototype, into src/data/rainQld.ts. Goondiwindi and Charters Towers come from the
// prototype (scripts/extract-rain.mjs). Run it again only to add a town: node scripts/fetch-rain.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ALPHA = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_-';
const TOWNS = {
  stg: ['St George', -28.04, 148.58],
  dby: ['Dalby', -27.18, 151.26],
  emd: ['Emerald', -23.53, 148.16],
  mbh: ['Moranbah', -22.0, 148.05],
  mky: ['Mackay', -21.14, 149.19],
  isa: ['Mount Isa', -20.73, 139.49],
  wei: ['Weipa', -12.63, 141.88],
};
const out = {};
for (const [k, [name, lat, lon]] of Object.entries(TOWNS)) {
  const u = `https://archive-api.open-meteo.com/v1/archive?latitude=${lat}&longitude=${lon}&start_date=1995-01-01&end_date=2024-12-31&daily=precipitation_sum&timezone=Australia%2FBrisbane`;
  const j = await (await fetch(u)).json();
  const p = j.daily.precipitation_sum;
  if (p.length !== 10958) throw new Error(`${name}: ${p.length} days`);
  out[k] = p.map((mm) => ALPHA[Math.min(63, Math.round(mm || 0))]).join('');
  console.log(`${name}: ${Math.round(p.reduce((a, x) => a + (x || 0), 0) / 30)} mm a year`);
}
const src = `// Real daily rainfall, 1995 to 2024, from the Open-Meteo historical weather archive, for the towns added after the
// prototype. Same encoding as rain.ts. Generated by scripts/fetch-rain.mjs. Don't edit by hand.

export const RAIN_QLD = {
${Object.entries(out).map(([k, s]) => `  ${k}: '${s}',`).join('\n')}
} as const;
`;
writeFileSync(fileURLToPath(new URL('../src/data/rainQld.ts', import.meta.url)), src);
